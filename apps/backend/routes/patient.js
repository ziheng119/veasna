// routes/patient.js
const express = require("express");
const router = express.Router();
const { integerParams } = require("../utils/validation");
// Non-integer IDs in the URL are rejected with 400 before reaching the database.
integerParams(router, ["id"]);
const db = require("../config/db");
const { authenticateToken, requireRole } = require("../routes/auth");
const { normalizeSexToEnum } = require("../utils/sex");

// Responses rely on Express's content-hash ETag (app.set("etag", ...)), so any change to a
// patient, visit or station record yields a new ETag and clients never get a stale 304.

const DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/;
function isValidDate(value) {
  return typeof value === "string" && DATE_PATTERN.test(value) &&
    Number.isFinite(Date.parse(value)) && new Date(value).toISOString().slice(0, 10) === value;
}

// GET /api/patient/:id - Get patient information with visits list (lightweight)
router.get(
  "/:id",
  authenticateToken,
  requireRole(["any"]),
  async (req, res) => {
    const { id } = req.params;

    if (!id) {
      return res.status(400).json({ error: "Patient ID is required" });
    }

    try {
      // Get basic patient information
      const patientQuery = `
      SELECT 
        p.id,
        p.face_id,
        p.location_id,
        p.english_name,
        p.khmer_name,
        p.date_of_birth,
        p.sex,
        p.address,
        p.phone_number,
        p.last_updated_at,
        p.created_at,
        l.name AS location_name
      FROM patients p
      LEFT JOIN locations l ON p.location_id = l.id
      WHERE p.id = $1
    `;
      const patientResult = await db.query(patientQuery, [id]);

      if (patientResult.rows.length === 0) {
        return res.status(404).json({ error: "Patient not found" });
      }

      const patient = patientResult.rows[0];

      // Get visits list (lightweight - just basic info)
      const visitsQuery = `
      SELECT 
        v.id AS visit_id,
        v.queue_no,
        v.visit_date,
        v.last_updated_at,
        l.name AS location_name,
        -- Check which sections have data
        CASE WHEN vt.id IS NOT NULL THEN true ELSE false END AS has_vitals,
        CASE WHEN pc.id IS NOT NULL THEN true ELSE false END AS has_presenting_complaint,
        CASE WHEN s.id IS NOT NULL THEN true ELSE false END AS has_seva,
        CASE WHEN pt.id IS NOT NULL THEN true ELSE false END AS has_physiotherapy,
        CASE WHEN c.id IS NOT NULL THEN true ELSE false END AS has_consultation
      FROM visits v
      LEFT JOIN locations l ON v.location_id = l.id
      LEFT JOIN vitals vt ON v.id = vt.visit_id
      LEFT JOIN presenting_complaint pc ON v.id = pc.visit_id
      LEFT JOIN seva s ON v.id = s.visit_id
      LEFT JOIN physiotherapy pt ON v.id = pt.visit_id
      LEFT JOIN consultation c ON v.id = c.visit_id
      WHERE v.patient_id = $1
      ORDER BY v.visit_date DESC, v.created_at DESC
    `;
      const visitsResult = await db.query(visitsQuery, [id]);

      res.status(200).json({
        patient: patient,
        visits: visitsResult.rows,
      });
    } catch (err) {
      console.error("Error fetching patient data:", err);
      res.status(500).json({ error: "Internal server error" });
    }
  },
);

// PUT /api/patient/:id - Admin correction of patient demographic details.
// Body: { english_name, date_of_birth (YYYY-MM-DD), sex (M/F), khmer_name?, phone_number?,
//         address?, location_id? }. face_id is regenerated by a database trigger.
router.put(
  "/:id",
  authenticateToken,
  requireRole(["admin"]),
  async (req, res) => {
    const { id } = req.params;

    if (!id || !Number.isInteger(Number(id)) || Number(id) < 1) {
      return res
        .status(400)
        .json({ error: "Patient ID must be a positive integer" });
    }

    const {
      english_name,
      khmer_name,
      date_of_birth,
      sex,
      phone_number,
      address,
      location_id,
    } = req.body;
    const last_updated_by = req.user && req.user.id;
    const normalizedSex = normalizeSexToEnum(sex);
    // Omitted keeps the registered location; older clients do not send it.
    const locationId = location_id === undefined || location_id === null ? null : Number(location_id);

    if (!english_name || !String(english_name).trim()) {
      return res.status(400).json({ error: "English name is required" });
    }
    if (!isValidDate(date_of_birth)) {
      return res.status(400).json({ error: "A valid date of birth (YYYY-MM-DD) is required" });
    }
    if (!normalizedSex) {
      return res.status(400).json({ error: "Sex is required (M or F)" });
    }
    if (locationId !== null && (!Number.isSafeInteger(locationId) || locationId < 1)) {
      return res.status(400).json({ error: "location_id must be a positive integer" });
    }
    if (!last_updated_by) {
      return res.status(401).json({ error: "Authentication required" });
    }

    try {
      const updateQuery = `
      WITH updated AS (
        UPDATE patients
        SET
          english_name = $1,
          khmer_name = $2,
          date_of_birth = $3,
          sex = $4,
          phone_number = $5,
          address = $6,
          location_id = COALESCE($9, location_id),
          last_updated_by = $7,
          last_updated_at = NOW()
        WHERE id = $8
        RETURNING *
      )
      SELECT
        u.id,
        u.face_id,
        u.location_id,
        u.english_name,
        u.khmer_name,
        TO_CHAR(u.date_of_birth, 'YYYY-MM-DD') AS date_of_birth,
        u.sex,
        u.address,
        u.phone_number,
        u.last_updated_at,
        u.last_updated_by,
        u.created_at,
        l.name AS location_name
      FROM updated u
      LEFT JOIN locations l ON u.location_id = l.id
    `;

      const result = await db.query(updateQuery, [
        String(english_name).trim(),
        khmer_name || null,
        date_of_birth,
        normalizedSex,
        phone_number || null,
        address || null,
        last_updated_by,
        id,
        locationId,
      ]);

      if (result.rows.length === 0) {
        return res.status(404).json({ error: "Patient not found" });
      }

      res.status(200).json({ patient: result.rows[0] });
    } catch (err) {
      if (err && err.code === "23503") {
        return res.status(400).json({ error: "Location not found" });
      }
      console.error("Error updating patient data:", err);
      res.status(500).json({ error: "Internal server error" });
    }
  },
);

// GET /api/patient/visit/:id - Get complete visit details. Each station section is null
// when it was never recorded for the visit.
router.get(
  "/visit/:id",
  authenticateToken,
  requireRole(["any"]),
  async (req, res) => {
    const { id } = req.params;

    if (!id) {
      return res.status(400).json({ error: "Visit ID is required" });
    }

    try {
      // Get complete visit data
      const visitQuery = `
        SELECT 
          v.id AS visit_id,
          v.patient_id,
          v.queue_no,
          v.visit_date,
          v.location_id,
          v.completed_at,
          v.last_updated_at AS visit_last_updated,
          v.created_at AS visit_created_at,
          l.name AS location_name,
          
          -- Vitals
          vt.id AS vitals_id,
          vt.height,
          vt.weight,
          vt.bmi,
          vt.below_3rd_percentile,
          vt.bp_systolic,
          vt.bp_diastolic,
          vt.temperature,
          vt.notes AS vitals_notes,
          
          -- HEF
          h.id AS hef_id,
          h.know_of_hef,
          h.has_hef,
          h.notes AS hef_notes,
          
          -- Visual Acuity
          va.id AS visual_acuity_id,
          va.left_with_pinhole,
          va.left_without_pinhole,
          va.right_with_pinhole,
          va.right_without_pinhole,
          va.notes AS visual_acuity_notes,
          
          -- Presenting Complaint
          pc.id AS complaint_id,
          pc.history AS complaint_history,
          pc.red_flags,
          pc.systems_review AS complaint_systems_review,
          pc.drug_allergies,
          
          -- History
          hist.id AS history_id,
          hist.past AS history_past,
          hist.drug_and_treatment,
          hist.family AS history_family,
          hist.social AS history_social,
          hist.systems_review AS history_systems_review,
          
          -- SEVA
          s.id AS seva_id,
          s.left_with_pinhole_new AS seva_left_with_pinhole,
          s.left_without_pinhole_new AS seva_left_without_pinhole,
          s.right_with_pinhole_new AS seva_right_with_pinhole,
          s.right_without_pinhole_new AS seva_right_without_pinhole,
          s.diagnosis AS seva_diagnosis,
          s.date_of_referral AS seva_referral_date,
          s.referral AS seva_referral,
          s.notes AS seva_notes,
          
          -- Physiotherapy
          pt.id AS physio_id,
          pt.notes AS physio_notes,
          
          -- Consultation
          c.id AS consultation_id,
          c.notes AS consultation_notes,
          c.prescription,
          c.require_referral,
          c.condition_categories,

          -- TB screening
          tb.id AS tb_id,
          tb.red_flags AS tb_red_flags,
          tb.flag_notes AS tb_flag_notes,
          tb.status AS tb_status,
          tb.doctor_notes AS tb_doctor_notes,
          tb.reviewed_at AS tb_reviewed_at

        FROM visits v
        LEFT JOIN locations l ON v.location_id = l.id
        LEFT JOIN vitals vt ON v.id = vt.visit_id
        LEFT JOIN hef h ON v.id = h.visit_id
        LEFT JOIN visual_acuity va ON v.id = va.visit_id
        LEFT JOIN presenting_complaint pc ON v.id = pc.visit_id
        LEFT JOIN history hist ON v.id = hist.visit_id
        LEFT JOIN seva s ON v.id = s.visit_id
        LEFT JOIN physiotherapy pt ON v.id = pt.visit_id
        LEFT JOIN consultation c ON v.id = c.visit_id
        LEFT JOIN tb_screening tb ON v.id = tb.visit_id
        WHERE v.id = $1
      `;
      const visitResult = await db.query(visitQuery, [id]);

      if (visitResult.rows.length === 0) {
        return res.status(404).json({ error: "Visit not found" });
      }

      const visit = visitResult.rows[0];

      // Get painpoints if physiotherapy exists
      let painpoints = [];
      if (visit.physio_id) {
        const painpointsQuery = `
          SELECT 
            id,
            x_coord,
            y_coord,
            last_updated_at
          FROM painpoints
          WHERE physiotherapy_id = $1
          ORDER BY created_at ASC
        `;
        const painpointsResult = await db.query(painpointsQuery, [
          visit.physio_id,
        ]);
        painpoints = painpointsResult.rows;
      }

      // Get referrals for this visit (changed from consultation-based to visit-based)
      let referrals = [];
      const referralQuery = `
        SELECT 
          id,
          referral_date,
          referral_type,
          illness,
          duration,
          reason,
          signature,
          signer_name,
          signed_at,
          last_updated_at
        FROM referral
        WHERE visit_id = $1
        ORDER BY referral_date DESC
      `;
      const referralResult = await db.query(referralQuery, [id]);
      referrals = referralResult.rows;

      // Structure the response
      const response = {
        visit_id: visit.visit_id,
        patient_id: visit.patient_id,
        queue_no: visit.queue_no,
        visit_date: visit.visit_date,
        location_id: visit.location_id,
        location_name: visit.location_name,
        completed_at: visit.completed_at,
        last_updated_at: visit.visit_last_updated,
        created_at: visit.visit_created_at,

        vitals:
          visit.vitals_id !== null
            ? {
                height: visit.height,
                weight: visit.weight,
                bmi: visit.bmi,
                below_3rd_percentile: visit.below_3rd_percentile,
                bp_systolic: visit.bp_systolic,
                bp_diastolic: visit.bp_diastolic,
                temperature: visit.temperature,
                notes: visit.vitals_notes,
              }
            : null,

        hef:
          visit.hef_id !== null
            ? {
                know_of_hef: visit.know_of_hef,
                has_hef: visit.has_hef,
                notes: visit.hef_notes,
              }
            : null,

        visual_acuity:
          visit.visual_acuity_id !== null
            ? {
                left_with_pinhole: visit.left_with_pinhole,
                left_without_pinhole: visit.left_without_pinhole,
                right_with_pinhole: visit.right_with_pinhole,
                right_without_pinhole: visit.right_without_pinhole,
                notes: visit.visual_acuity_notes,
              }
            : null,

        presenting_complaint:
          visit.complaint_id !== null
            ? {
                history: visit.complaint_history,
                red_flags: visit.red_flags,
                systems_review: visit.complaint_systems_review,
                drug_allergies: visit.drug_allergies,
              }
            : null,

        history:
          visit.history_id !== null
            ? {
                past: visit.history_past,
                drug_and_treatment: visit.drug_and_treatment,
                family: visit.history_family,
                social: visit.history_social,
                systems_review: visit.history_systems_review,
              }
            : null,

        seva:
          visit.seva_id !== null
            ? {
                left_with_pinhole_new: visit.seva_left_with_pinhole,
                left_without_pinhole_new: visit.seva_left_without_pinhole,
                right_with_pinhole_new: visit.seva_right_with_pinhole,
                right_without_pinhole_new: visit.seva_right_without_pinhole,
                diagnosis: visit.seva_diagnosis,
                date_of_referral: visit.seva_referral_date,
                referral: visit.seva_referral,
                notes: visit.seva_notes,
              }
            : null,

        tb: visit.tb_id
          ? {
              red_flags: visit.tb_red_flags,
              flag_notes: visit.tb_flag_notes,
              status: visit.tb_status,
              doctor_notes: visit.tb_doctor_notes,
              reviewed_at: visit.tb_reviewed_at,
            }
          : null,

        physiotherapy: visit.physio_id
          ? {
              notes: visit.physio_notes,
              painpoints: painpoints,
            }
          : null,

        consultation: visit.consultation_id
          ? {
              notes: visit.consultation_notes,
              prescription: visit.prescription,
              require_referral: visit.require_referral,
              condition_categories: visit.condition_categories,
            }
          : null,

        // Referrals are now at visit level, not nested in consultation
        referrals: referrals,
      };

      res.status(200).json(response);
    } catch (err) {
      console.error("Error fetching visit data:", err);
      res.status(500).json({ error: "Internal server error" });
    }
  },
);

module.exports = router;
