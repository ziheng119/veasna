    id SERIAL PRIMARY KEY,
    visit_id INT UNIQUE NOT NULL REFERENCES visits(id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    notes TEXT DEFAULT '',
    prescription TEXT NOT NULL,
