-- Enum Types
CREATE TYPE sex_type AS ENUM ('M', 'F');

-- Users
CREATE TABLE users (
    id SERIAL PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    password_hash TEXT,
    role VARCHAR(20) NOT NULL DEFAULT 'user',
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT NOW()
);

CREATE UNIQUE INDEX users_username_lower_unique ON users (LOWER(username));

-- Locations
CREATE TABLE locations (
    id SERIAL PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT NOW()
);

-- Patients
CREATE TABLE patients (
    id SERIAL PRIMARY KEY,
    face_id VARCHAR(40),                                -- Generated by trg_set_patient_face_id; not unique
    location_id INT REFERENCES locations(id),           -- Will not be deleted, set inactive only
    english_name VARCHAR(255),
    khmer_name VARCHAR(255),
    date_of_birth DATE,
    sex sex_type,
    address TEXT,
    phone_number VARCHAR(50),
    last_updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    last_updated_by INT NOT NULL REFERENCES users(id) ON UPDATE CASCADE,           -- Will not be deleted, set inactive only
    created_at TIMESTAMP DEFAULT NOW()
);

-- Face ID: first 3 characters of the English name + first 3 of the Khmer name + date of birth (DDMMYYYY).
CREATE OR REPLACE FUNCTION patient_face_id(english_name TEXT, khmer_name TEXT, date_of_birth DATE)
RETURNS TEXT AS $$
    SELECT NULLIF(
        UPPER(
            LEFT(regexp_replace(COALESCE(english_name, ''), '\s', '', 'g'), 3)
            || LEFT(regexp_replace(COALESCE(khmer_name, ''), '\s', '', 'g'), 3)
        ) || COALESCE(TO_CHAR(date_of_birth, 'DDMMYYYY'), ''),
        ''
    );
$$ LANGUAGE sql IMMUTABLE;

CREATE OR REPLACE FUNCTION set_patient_face_id()
RETURNS TRIGGER AS $$
BEGIN
    NEW.face_id := patient_face_id(NEW.english_name, NEW.khmer_name, NEW.date_of_birth);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_set_patient_face_id
BEFORE INSERT OR UPDATE ON patients
FOR EACH ROW
EXECUTE FUNCTION set_patient_face_id();


-- Visits
CREATE TABLE visits (
    id SERIAL PRIMARY KEY,
    patient_id INT NOT NULL REFERENCES patients(id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    location_id INT REFERENCES locations(id)
        ON DELETE SET NULL ON UPDATE CASCADE,
    queue_no VARCHAR(50) NOT NULL,
    visit_date DATE NOT NULL,
    completed_at TIMESTAMP NULL,
    last_updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    last_updated_by INT NOT NULL REFERENCES users(id) ON UPDATE CASCADE,
    created_at TIMESTAMP DEFAULT NOW()
);

-- Visit stations: the stations a visit is indicated for, in order.
-- The first one not yet completed is the queue the patient is currently in.
CREATE TABLE visit_stations (
    id SERIAL PRIMARY KEY,
    visit_id INT NOT NULL REFERENCES visits(id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    station VARCHAR(30) NOT NULL
        CONSTRAINT visit_stations_station_check
        CHECK (station IN ('tb', 'triage', 'seva', 'physiotherapy', 'consultation')),
    position INT NOT NULL,                 -- remaining route order; may change when a station is deferred or revisited
    entered_at TIMESTAMP NULL,
    completed_at TIMESTAMP NULL,
    last_updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    last_updated_by INT NOT NULL REFERENCES users(id) ON UPDATE CASCADE,
    created_at TIMESTAMP DEFAULT NOW(),
    UNIQUE (visit_id, station)
);

CREATE INDEX visit_stations_pending_idx
    ON visit_stations (visit_id, position) WHERE completed_at IS NULL;

-- TB screening. A flagged visit is queued at the TB tent first and cannot be seen at any other
-- station until a TB doctor clears it. status: suspected, cleared, tb_likely (TB not ruled out).
CREATE TABLE tb_screening (
    id SERIAL PRIMARY KEY,
    visit_id INT UNIQUE NOT NULL REFERENCES visits(id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    red_flags TEXT[] NOT NULL DEFAULT '{}',
    flag_notes TEXT NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL DEFAULT 'suspected'
        CHECK (status IN ('suspected', 'cleared', 'tb_likely')),
    doctor_notes TEXT NOT NULL DEFAULT '',
    flagged_by INT NOT NULL REFERENCES users(id) ON UPDATE CASCADE,
    flagged_at TIMESTAMP NOT NULL DEFAULT NOW(),
    reviewed_by INT NULL REFERENCES users(id) ON UPDATE CASCADE,
    reviewed_at TIMESTAMP NULL,
    last_updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    last_updated_by INT NOT NULL REFERENCES users(id) ON UPDATE CASCADE,
    created_at TIMESTAMP DEFAULT NOW()
);

-- Vitals
CREATE TABLE vitals (
    id SERIAL PRIMARY KEY,
    visit_id INT UNIQUE NOT NULL REFERENCES visits(id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    height NUMERIC NOT NULL CHECK (height > 0),
    weight NUMERIC NOT NULL CHECK (weight > 0),
    bmi NUMERIC NOT NULL CHECK (bmi > 0),
    below_3rd_percentile BOOLEAN NOT NULL,
    bp_systolic INT NOT NULL,
    bp_diastolic INT NOT NULL,
    temperature NUMERIC NOT NULL,
    notes TEXT DEFAULT '',
    last_updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    last_updated_by INT NOT NULL REFERENCES users(id) ON UPDATE CASCADE,
    created_at TIMESTAMP DEFAULT NOW()
);

